# 编写一个函数 calculate_salary。

# 要求：
# 1. 接收两个参数：基本工资、奖金。
# 2. 计算总工资。
# 3. 使用 return 返回总工资。
# 4. 在函数外部接收返回值。
# 5. 打印最终工资。
# 测试数据：
# - 基本工资：10000
# - 奖金：2000

def calculate_salary(basicSalary , winSalary) :
    return basicSalary + winSalary

